  function scoreText(text) {
    if (!text || text.trim().length < 40) return 0;
    let total = 0;

    for (const p of HIGH_TEXT) if (p.test(text)) total += 3;

    let med = 0;
    for (const p of MEDIUM_TEXT) if (p.test(text)) med += 1.5;
    total += Math.min(med, 6);

    let low = 0;
    for (const p of LOW_TEXT) if (p.test(text)) low += 0.5;
    total += Math.min(low, 3);

    for (const kw of cfg.customKeywords) if (kw && text.toLowerCase().includes(kw.toLowerCase())) total += 1.5;

    // Slop emoji density
    const hitEmoji = SLOP_EMOJI.filter(e => text.includes(e)).length;
    if (hitEmoji >= 4) total += 2;
    else if (hitEmoji >= 2) total += 0.8;

    // ── Statistical signals ────────────────────────────────────────────────────

    // 1. Transition word stacking (AI loves chaining: "Furthermore... Moreover... Additionally...")
    const transitions = (text.match(/\b(additionally|furthermore|moreover|in addition|what'?s more|on the other hand|in contrast|consequently|as a result|therefore|thus|hence|nevertheless|nonetheless)\b/gi) || []).length;
    if (transitions >= 3) total += 2.5;
    else if (transitions >= 2) total += 1.2;
    else if (transitions >= 1) total += 0.4;

    // 2. Em dash overuse — AI loves em dashes
    const emDashes = (text.match(/—/g) || []).length;
    if (emDashes >= 3) total += 1.5;
    else if (emDashes >= 1) total += 0.4;

    // 3. Contraction absence (very formal = AI)
    if (text.length > 200 && !/\b(don'?t|can'?t|won'?t|it'?s|I'?m|you'?re|they'?re|we'?re|couldn'?t|shouldn'?t|wouldn'?t|didn'?t|isn'?t|aren'?t|wasn'?t|weren'?t|haven'?t|hadn'?t|doesn'?t|hasn'?t)\b/i.test(text)) total += 1.2;

    // 4. Sentence length CV (coefficient of variation) — AI = suspiciously uniform
    const sentences = text.match(/[^.!?]+[.!?]+/g) || [];
    if (sentences.length >= 4) {
      const lens = sentences.map(s => s.trim().length);
      const avg = lens.reduce((a, b) => a + b, 0) / lens.length;
      const variance = lens.reduce((a, b) => a + Math.pow(b - avg, 2), 0) / lens.length;
      const cv = avg > 0 ? Math.sqrt(variance) / avg : 1;
      if (cv < 0.20 && sentences.length >= 6) total += 2;    // extremely uniform
      else if (cv < 0.30 && sentences.length >= 5) total += 1;
      else if (variance < 150 && avg > 60) total += 0.5;
    }

    // 5. TTR — Type-Token Ratio (AI reuses words more than humans)
    const words = text.toLowerCase().match(/\b[a-z]{3,}\b/g) || [];
    if (words.length >= 50) {
      const sample = words.slice(0, 200);
      const ttr = new Set(sample).size / sample.length;
      if (ttr < 0.35) total += 2;       // very low diversity
      else if (ttr < 0.45) total += 0.9;
    }

    // 6. Parallel bullet structure (AI loves perfectly parallel lists)
    const bullets = text.match(/^[-•*]\s+.{10,}$/gm) || [];
    if (bullets.length >= 4) {
      const blens = bullets.map(b => b.split(/\s+/).length);
      const bavg = blens.reduce((a,b)=>a+b,0)/blens.length;
      const bvar = blens.reduce((a,b)=>a+Math.pow(b-bavg,2),0)/blens.length;
      if (bvar < 8) total += 1.5;  // suspiciously parallel bullet points
    }

    // 7. Numbered list with round count (AI loves lists of exactly 5, 7, 10)
    const numberedItems = (text.match(/^\d+[.)]\s+/gm) || []).length;
    if ([5, 7, 10, 3].includes(numberedItems)) total += 0.6;

    return total;
  }

  // ─── BLOCK UI ────────────────────────────────────────────────────────────────
  function blockEl(el, reason, type) {
    if (!el || el.dataset.aisbBlocked) return;
    el.dataset.aisbBlocked = '1';
    const orig = el.style.display || '';
    el.style.display = 'none';

    const pill = document.createElement('div');
    pill.dataset.aisbPill = '1';
    pill.style.cssText = 'display:flex;align-items:center;gap:8px;border:1px solid rgba(124,58,237,0.4);border-radius:8px;padding:9px 14px;margin:4px 0;font-size:12px;color:#a78bfa;background:rgba(15,10,30,0.9);cursor:pointer;font-family:system-ui,-apple-system,sans-serif;user-select:none;width:100%;max-width:600px;box-sizing:border-box;backdrop-filter:blur(4px);';
    const icons = { image: '🖼️', video: '🎬', text: '📝', content: '🤖' };
    const icon = icons[type] || '🛡️';
    pill.innerHTML = `<span style="font-size:14px;flex-shrink:0">${icon}</span><span style="color:#c4b5fd;font-weight:600;flex:1">AI ${type || 'content'} blocked</span><span style="opacity:0.4;font-size:10px;flex-shrink:0;white-space:nowrap">click to reveal</span>`;
    pill.title = reason || 'AI-generated content';

    pill.addEventListener('mouseenter', () => { pill.style.borderColor = 'rgba(124,58,237,0.7)'; });
    pill.addEventListener('mouseleave', () => { pill.style.borderColor = 'rgba(124,58,237,0.4)'; });
    pill.addEventListener('click', () => {
      el.style.display = orig;
      delete el.dataset.aisbBlocked;
      pill.remove();
      notifyBg('UNBLOCK', { hostname, type });
    });

    if (el.parentNode) el.parentNode.insertBefore(pill, el);
    notifyBg('BLOCK_DETECTED', { hostname, contentType: type, reason });
  }

  function notifyBg(type, data) {
    try { chrome.runtime.sendMessage({ type, ...data }); } catch (_) {}
  }

  // ─── CONTAINER FINDER ────────────────────────────────────────────────────────
  function bestContainer(el, maxDepth) {
    maxDepth = maxDepth || 8;
    const STOP_TAGS = new Set(['ARTICLE', 'FIGURE', 'SECTION', 'LI', 'BLOCKQUOTE']);
    const STOP_RX = /\b(tweet|post|card|feed[_-]?item|media[_-]?wrap|photo[_-]?wrap|image[_-]?container|story[_-]?card|attachment|reel|clip|video[_-]?wrap|content[_-]?block|ugc)\b/i;
    let node = el.parentElement;
    let d = 0;
    while (node && node !== document.body && d < maxDepth) {
      if (STOP_TAGS.has(node.tagName)) return node;
      const sig = (node.className || '') + '|' + (node.getAttribute('data-testid') || '') + '|' + (node.id || '') + '|' + (node.getAttribute('role') || '');
      if (STOP_RX.test(sig)) return node;
      node = node.parentElement;
      d++;
    }
    return el.parentElement || el;
  }

  // ─── IMAGE CHECKING ───────────────────────────────────────────────────────────
  function getImgSrc(img) {
    return img.src || img.getAttribute('data-src') || img.getAttribute('data-lazy-src') || img.getAttribute('data-original') || img.getAttribute('srcset') || '';
  }

  function checkImageByCDN(src) {
    return AI_CDN_PATTERNS.some(p => p.test(src));
  }

  function checkImageByMeta(img) {
    const meta = [img.alt, img.title, img.getAttribute('aria-label'), img.getAttribute('data-alt')].filter(Boolean).join(' ');
    return AI_META_PATTERNS.some(p => p.test(meta));
  }

  function checkImageByContext(img) {
    // Look for platform AI labels in the surrounding post/card
    const wrap = img.closest('article, figure, [data-testid], [role="article"], [class*="post"], [class*="card"], [class*="tweet"], [class*="reel"], [class*="story"]') || img.parentElement;
    if (!wrap) return false;
    const txt = wrap.innerText || wrap.textContent || '';
    return PLATFORM_LABELS.some(p => p.test(txt));
  }

  function processImage(img) {
    if (img.dataset.aisbImg) return;
    img.dataset.aisbImg = '1';
    const src = getImgSrc(img);

    let reason = null;
    let type = 'image';

    if (src && checkImageByCDN(src)) {
      reason = 'Known AI image CDN: ' + src.slice(0, 60);
    } else if (checkImageByMeta(img)) {
      reason = 'Alt text indicates AI: ' + (img.alt || '').slice(0, 60);
    } else if (checkImageByContext(img)) {
      reason = 'Platform AI badge detected nearby';
    }

    // Guilt by association — if post text scores as AI, images inside are probably AI
    if (!reason) {
      const wrap = img.closest('article, [data-testid="tweet"], [role="article"], [class*="post"], [class*="card"], [class*="feed-item"], [class*="update"]') || img.parentElement;
      if (wrap) {
        const txt = (wrap.innerText || wrap.textContent || '').slice(0, 1200);
        if (txt.length > 80 && scoreText(txt) >= THRESHOLDS.aggressive) {
          reason = 'AI text context (guilt by association)';
        }
      }
    }

    // Send to background for C2PA / deeper check
    if (!reason && src && src.startsWith('http')) {
      notifyBg('CHECK_IMAGE', { src, hostname });
    }

    if (reason) {
      const container = bestContainer(img);
      if (!container.dataset.aisbBlocked) blockEl(container, reason, type);
    }
  }

  // ─── VIDEO CHECKING ───────────────────────────────────────────────────────────
  function processVideo(el) {
    if (el.dataset.aisbVid) return;
    el.dataset.aisbVid = '1';
    const src = el.src || el.getAttribute('data-src') || '';
    const poster = el.poster || el.getAttribute('data-poster') || '';

    // Check video src against AI video CDNs
    const AI_VIDEO = [/runwayml\.com/i, /pika\.art/i, /pika-videos/i, /sora\.com/i, /kling\.ai/i, /replicate\.delivery/i, /klingai\.com/i, /lumalabs\.ai/i, /haiper\.ai/i, /hailuoai\.com/i, /minimax\.io/i, /luma-/i];
    const bySrc = AI_VIDEO.some(p => p.test(src));

    // Check surrounding context for labels
    const wrap = el.closest('article, [data-testid], [class*="post"], [class*="reel"], [class*="story"], [class*="card"]') || el.parentElement;
    const txt = wrap ? (wrap.innerText || wrap.textContent || '') : '';
    const byCtx = PLATFORM_LABELS.some(p => p.test(txt));

    if (bySrc || byCtx) {
      const container = bestContainer(el);
      if (!container.dataset.aisbBlocked) blockEl(container, 'AI video detected', 'video');
      return;
    }

    // Send poster thumbnail for deep C2PA + visual analysis
    if (poster && poster.startsWith('http')) {
      notifyBg('CHECK_IMAGE', { src: poster, hostname, isVideoPoster: true });
    }

    // On X: portrait-format video (9:16) with no text in the tweet = high AI signal
    // Real phone videos are almost never posted to X as pure video-only tweets
    if (IS_X && wrap) {
      const hasText = (txt.replace(/\s/g, '').length > 30);
      const isPortrait = el.videoWidth > 0 && el.videoHeight > 0
        ? el.videoHeight > el.videoWidth * 1.3
        : (el.offsetHeight > el.offsetWidth * 1.3);
      if (!hasText && isPortrait) {
        const container = bestContainer(el);
        if (!container.dataset.aisbBlocked) blockEl(container, 'Unlabeled portrait AI video (X)', 'video');
      }
    }
  }

  // ─── TWEET / POST CHECKING (X-specific) ──────────────────────────────────────
  function processTweet(article) {
    if (article.dataset.aisbTweet) return;
    article.dataset.aisbTweet = '1';
    const txt = article.innerText || article.textContent || '';
    const threshold = THRESHOLDS[cfg.sensitivity] ?? 1.8;

    if (PLATFORM_LABELS.some(p => p.test(txt))) {
      if (!article.dataset.aisbBlocked) blockEl(article, 'Grok / AI content label', 'content');
      return;
    }
    if (scoreText(txt) >= threshold) {
      if (!article.dataset.aisbBlocked) blockEl(article, 'AI-generated text patterns', 'text');
    }
  }

