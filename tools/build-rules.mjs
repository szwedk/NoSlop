#!/usr/bin/env node
// Generates Extension/Resources/rules.js from Extension/Resources/rules.json.
// rules.js is a plain classic script (no modules) so it can be the first file in
// manifest content_scripts[].js. Run: `npm run build:rules`. A test asserts both are in sync.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'Extension/Resources/rules.json');
const dst = path.join(root, 'Extension/Resources/rules.js');

export function buildRulesJs(jsonText) {
  const rules = JSON.parse(jsonText); // validates
  // Compile-check every regex the way the scorer will (flags "iu").
  (function walk(o) {
    if (Array.isArray(o)) return o.forEach(walk);
    if (o && typeof o === 'object') {
      for (const [k, v] of Object.entries(o)) {
        if ((k === 'regex' || /Regex$/.test(k)) && typeof v === 'string') new RegExp(v, 'iu');
        else walk(v);
      }
    }
  })(rules);
  const body = JSON.stringify(rules, null, 2)
    // Keep the generated file safe inside a <script>-like context and in strict parsers.
    .split(String.fromCharCode(0x2028)).join('\\u2028').split(String.fromCharCode(0x2029)).join('\\u2029');
  return `// GENERATED by tools/build-rules.mjs from rules.json — DO NOT EDIT. Run \`npm run build:rules\`.\n` +
    `/* NoSlop rules ${rules.version} */\n` +
    `globalThis.NoSlop = globalThis.NoSlop || {};\n` +
    `NoSlop.rules = ${body};\n`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = buildRulesJs(fs.readFileSync(src, 'utf8'));
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(dst) ? fs.readFileSync(dst, 'utf8') : '';
    if (cur !== out) { console.error('rules.js is out of date; run `npm run build:rules`'); process.exit(1); }
    console.log('rules.js is in sync');
  } else {
    fs.writeFileSync(dst, out);
    console.log(`wrote ${path.relative(root, dst)} (${out.length} bytes)`);
  }
}
