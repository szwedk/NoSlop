#!/usr/bin/env node
// NoSlop — Chrome build (docs/DESIGN.md §9).
//
//   Extension/Resources  ->  dist/chrome
//
// What it does, in order:
//   1. copies the Safari web-extension folder verbatim (minus .DS_Store and similar);
//   2. rewrites manifest.json for Chrome MV3:
//        background: { scripts:[...], persistent:false }  ->  { service_worker: "sw.js" }
//        (sw.js is generated: `globalThis.browser ??= chrome; importScripts('background.js')`)
//        content_scripts kept as-is (same files, same order, same run_at);
//        browser_specific_settings dropped;  action + icons ensured;
//        `nativeMessaging` permission dropped (no native host exists in Chrome; background.js fails open);
//   3. prepends the `globalThis.browser ??= chrome;` polyfill to every content script and to
//      popup/*.js (idempotent: a second build over the same text does not double it);
//   4. validates: the written manifest parses as JSON and EVERY file it references exists in the
//      output folder.
//
// Usage:  node tools/build-chrome.mjs [--src Extension/Resources] [--out dist/chrome] [--quiet]
//         npm run build:chrome
// Load unpacked in chrome://extensions for smoke tests. Plain ESM Node script (Node 20+).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULT_SRC = path.join(ROOT, 'Extension/Resources');
export const DEFAULT_OUT = path.join(ROOT, 'dist/chrome');

export const POLYFILL_LINE = 'globalThis.browser ??= chrome;';
export const POLYFILL_MARK = '/* noslop:chrome-polyfill */';
// One line so stack-trace line numbers of the original file shift by exactly 1.
export const POLYFILL = `${POLYFILL_MARK} ${POLYFILL_LINE}\n`;
export const SW_FILE = 'sw.js';
export const MIN_CHROME = '121';

const SKIP_NAMES = new Set(['.DS_Store', 'Thumbs.db', '.gitkeep']);

// --------------------------------------------------------------------------- fs helpers
function listFiles(dir, base = dir) {
  const out = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_NAMES.has(ent.name) || ent.name.startsWith('._')) continue;
    const abs = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...listFiles(abs, base));
    else if (ent.isFile()) out.push(path.relative(base, abs).split(path.sep).join('/'));
  }
  return out.sort();
}

export function copyTree(src, out) {
  const files = listFiles(src);
  for (const rel of files) {
    const dst = path.join(out, ...rel.split('/'));
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(path.join(src, ...rel.split('/')), dst);
  }
  return files;
}

// --------------------------------------------------------------------------- polyfill
// Idempotent: returns `text` unchanged when it already carries the marker in its first lines.
// If the file opens with a top-level "use strict" directive (possibly after leading comments),
// the polyfill is inserted right AFTER that directive so the directive keeps its prologue position.
export function hasPolyfill(text) {
  return text.split('\n', 5).some((l) => l.includes(POLYFILL_MARK));
}

function prologueEnd(text) {
  // Scan past leading whitespace and comments; if a "use strict" directive follows, return the
  // index just after it (including its optional semicolon and trailing newline). Else 0.
  let i = 0;
  const n = text.length;
  for (;;) {
    while (i < n && /\s/.test(text[i])) i++;
    if (text.startsWith('//', i)) { const nl = text.indexOf('\n', i); i = nl === -1 ? n : nl + 1; continue; }
    if (text.startsWith('/*', i)) { const e = text.indexOf('*/', i + 2); i = e === -1 ? n : e + 2; continue; }
    break;
  }
  const m = /^(['"])use strict\1\s*;?[ \t]*\r?\n?/.exec(text.slice(i));
  return m ? i + m[0].length : 0;
}

export function addPolyfill(text) {
  if (hasPolyfill(text)) return text;
  const at = prologueEnd(text);
  if (at === 0) return POLYFILL + text;
  const head = text.slice(0, at);
  const sep = head.endsWith('\n') ? '' : '\n';
  return head + sep + POLYFILL + text.slice(at);
}

// --------------------------------------------------------------------------- manifest
export function swSource(backgroundScripts) {
  const imports = backgroundScripts.map((s) => JSON.stringify(s)).join(', ');
  return [
    '// GENERATED by tools/build-chrome.mjs — Chrome MV3 service worker shell. DO NOT EDIT.',
    '// Safari runs background.js as a non-persistent background script; Chrome needs a service worker.',
    POLYFILL_LINE,
    `importScripts(${imports});`,
    '',
  ].join('\n');
}

export function rewriteManifest(input) {
  const m = JSON.parse(JSON.stringify(input)); // deep copy; never mutate the caller's object
  if (m.manifest_version !== 3) throw new Error(`manifest_version must be 3 (got ${m.manifest_version})`);

  // background: scripts[] (Safari) -> service_worker (Chrome)
  const bgScripts = Array.isArray(m.background?.scripts) && m.background.scripts.length
    ? m.background.scripts
    : (typeof m.background?.service_worker === 'string' && m.background.service_worker !== SW_FILE)
      ? [m.background.service_worker]
      : ['background.js'];
  m.background = { service_worker: SW_FILE };

  // content_scripts: kept verbatim (same files, same order, same run_at / all_frames / css)
  if (!Array.isArray(m.content_scripts) || !m.content_scripts.length) throw new Error('manifest has no content_scripts');

  // Safari-only block
  delete m.browser_specific_settings;

  // permissions: nativeMessaging needs a registered native host, which Chrome does not have; the
  // background's native() helper is try/catch and fails open, so dropping it just avoids the
  // "Communicate with cooperating native applications" install warning.
  if (Array.isArray(m.permissions)) m.permissions = m.permissions.filter((p) => p !== 'nativeMessaging');

  // icons + action
  if (!m.icons || !Object.keys(m.icons).length) {
    m.icons = { 48: 'images/icon-48.png', 96: 'images/icon-96.png', 128: 'images/icon-128.png' };
  }
  const action = m.action && typeof m.action === 'object' ? m.action : {};
  if (!action.default_popup) action.default_popup = 'popup/popup.html';
  if (!action.default_title) action.default_title = m.name || 'NoSlop';
  if (!action.default_icon) {
    action.default_icon = {};
    for (const k of ['48', '96', '128']) if (m.icons[k]) action.default_icon[k] = m.icons[k];
    if (!Object.keys(action.default_icon).length) action.default_icon = { ...m.icons };
  }
  m.action = action;
  delete m.browser_action; // MV2 leftover, never valid in MV3

  if (!m.minimum_chrome_version) m.minimum_chrome_version = MIN_CHROME;

  return { manifest: m, backgroundScripts: bgScripts };
}

// Every path a manifest can point at inside the extension folder (relative, no leading slash).
export function referencedFiles(m) {
  const refs = new Set();
  const add = (v) => { if (typeof v === 'string' && v && !/^(https?:|chrome:|\*)/.test(v)) refs.add(v.replace(/^\.?\//, '')); };
  const addMap = (o) => { if (o && typeof o === 'object') Object.values(o).forEach(add); };
  addMap(m.icons);
  if (m.background) {
    add(m.background.service_worker);
    (m.background.scripts || []).forEach(add);
    add(m.background.page);
  }
  for (const cs of m.content_scripts || []) { (cs.js || []).forEach(add); (cs.css || []).forEach(add); }
  if (m.action) { add(m.action.default_popup); addMap(m.action.default_icon); }
  if (m.options_ui) add(m.options_ui.page);
  add(m.options_page);
  add(m.devtools_page);
  if (m.side_panel) add(m.side_panel.default_path);
  if (m.chrome_url_overrides) addMap(m.chrome_url_overrides);
  if (m.sandbox) (m.sandbox.pages || []).forEach(add);
  for (const w of m.web_accessible_resources || []) {
    // MV3 form: [{resources:[...], matches:[...]}]; MV2 form: ["path", ...]
    if (typeof w === 'string') add(w);
    else (w.resources || []).forEach((r) => { if (!/[*?]/.test(r)) add(r); });
  }
  if (m.declarative_net_request) for (const r of m.declarative_net_request.rule_resources || []) add(r.path);
  if (m.default_locale) refs.add(`_locales/${m.default_locale}/messages.json`);
  return [...refs].sort();
}

export function validateOutput(out) {
  const problems = [];
  const manifestPath = path.join(out, 'manifest.json');
  let m;
  try { m = JSON.parse(fs.readFileSync(manifestPath, 'utf8')); }
  catch (e) { return { ok: false, problems: [`manifest.json unreadable or not valid JSON: ${e.message}`], manifest: null, referenced: [] }; }
  if (m.manifest_version !== 3) problems.push('manifest_version is not 3');
  if (!m.background || m.background.service_worker !== SW_FILE) problems.push(`background.service_worker is not "${SW_FILE}"`);
  if (m.background && 'scripts' in m.background) problems.push('background.scripts must not survive in the Chrome manifest');
  if ('browser_specific_settings' in m) problems.push('browser_specific_settings must be dropped');
  if (!m.action || !m.action.default_popup) problems.push('action.default_popup missing');
  if (!m.icons || !Object.keys(m.icons).length) problems.push('icons missing');
  const referenced = referencedFiles(m);
  for (const rel of referenced) {
    const abs = path.join(out, ...rel.split('/'));
    if (!fs.existsSync(abs) || !fs.statSync(abs).isFile()) problems.push(`referenced file missing: ${rel}`);
  }
  // Every content script must carry the polyfill (so `browser.*` resolves in Chrome).
  for (const cs of m.content_scripts || []) {
    for (const js of cs.js || []) {
      const abs = path.join(out, ...js.split('/'));
      if (fs.existsSync(abs) && !hasPolyfill(fs.readFileSync(abs, 'utf8'))) problems.push(`content script without polyfill: ${js}`);
    }
  }
  return { ok: problems.length === 0, problems, manifest: m, referenced };
}

// --------------------------------------------------------------------------- build
export function buildChrome({ src = DEFAULT_SRC, out = DEFAULT_OUT, quiet = true } = {}) {
  src = path.resolve(src);
  out = path.resolve(out);
  if (!fs.existsSync(path.join(src, 'manifest.json'))) throw new Error(`no manifest.json in ${src}`);
  if (out === src || src.startsWith(out + path.sep)) throw new Error('output folder must not contain the source');

  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  const copied = copyTree(src, out);

  const srcManifest = JSON.parse(fs.readFileSync(path.join(src, 'manifest.json'), 'utf8'));
  const { manifest, backgroundScripts } = rewriteManifest(srcManifest);

  // service worker shell
  fs.writeFileSync(path.join(out, SW_FILE), swSource(backgroundScripts));

  // polyfill: content scripts + popup/*.js (NOT background.js: sw.js sets `browser` before importScripts)
  const polyfilled = new Set();
  const targets = new Set();
  for (const cs of manifest.content_scripts) for (const js of cs.js || []) targets.add(js);
  const popupDir = path.join(out, 'popup');
  if (fs.existsSync(popupDir)) for (const rel of listFiles(popupDir)) if (rel.endsWith('.js')) targets.add(`popup/${rel}`);
  const popupFromAction = manifest.action?.default_popup;
  if (popupFromAction) {
    const dir = path.posix.dirname(popupFromAction);
    const absDir = path.join(out, ...dir.split('/'));
    if (fs.existsSync(absDir)) for (const rel of listFiles(absDir)) if (rel.endsWith('.js')) targets.add(path.posix.join(dir, rel));
  }
  // lib/tiktok-main.js runs in the PAGE world (web_accessible_resources) where `chrome` may be undefined: never polyfill it.
  targets.delete('lib/tiktok-main.js');
  for (const rel of [...targets].sort()) {
    if (/(^|\/)tiktok-main\.js$/.test(rel)) continue;
    const abs = path.join(out, ...rel.split('/'));
    if (!fs.existsSync(abs)) continue; // validation reports it below
    const before = fs.readFileSync(abs, 'utf8');
    const after = addPolyfill(before);
    if (after !== before) fs.writeFileSync(abs, after);
    polyfilled.add(rel);
  }

  fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

  const v = validateOutput(out);
  const result = { src, out, copied, manifest, backgroundScripts, polyfilled: [...polyfilled].sort(), referenced: v.referenced, problems: v.problems, ok: v.ok };
  if (!quiet) {
    console.log(`[build-chrome] ${copied.length} files copied -> ${path.relative(ROOT, out) || out}`);
    console.log(`[build-chrome] polyfilled: ${result.polyfilled.join(', ')}`);
    console.log(`[build-chrome] ${SW_FILE} imports: ${backgroundScripts.join(', ')}`);
  }
  if (!v.ok) {
    const err = new Error(`Chrome build invalid:\n  - ${v.problems.join('\n  - ')}`);
    err.result = result;
    throw err;
  }
  return result;
}

// --------------------------------------------------------------------------- CLI
function parseArgs(argv) {
  const o = { src: DEFAULT_SRC, out: DEFAULT_OUT, quiet: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--src') o.src = path.resolve(argv[++i]);
    else if (a.startsWith('--src=')) o.src = path.resolve(a.slice(6));
    else if (a === '--out') o.out = path.resolve(argv[++i]);
    else if (a.startsWith('--out=')) o.out = path.resolve(a.slice(6));
    else if (a === '--quiet' || a === '-q') o.quiet = true;
    else if (a === '--help' || a === '-h') { console.log('usage: node tools/build-chrome.mjs [--src DIR] [--out DIR] [--quiet]'); process.exit(0); }
    else { console.error(`unknown argument: ${a}`); process.exit(2); }
  }
  return o;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const opts = parseArgs(process.argv.slice(2));
  try {
    const r = buildChrome(opts);
    if (!opts.quiet) console.log(`[build-chrome] OK — manifest references ${r.referenced.length} files, all present. Load unpacked: ${r.out}`);
  } catch (e) {
    console.error(`[build-chrome] FAILED: ${e.message}`);
    process.exit(1);
  }
}
